    private val expected = intArrayOf(-1935013376, 179476272, -1473821733, 200726673, 477805082)

    private fun checksum(a: IntArray): Int {
        var h = 0
        for (v in a) h = h * 31 + v
        return h
    }

    @Test fun readsSizeFramesAndDuration() {
        val d = GifDecoder(gif)
        assertEquals(40, d.width)
        assertEquals(30, d.height)
        assertEquals(5, d.frameCount)
        assertEquals(50L + 100 + 30 + 100 + 70, d.durationMs)   // a 0 ms delay counts as 100 ms
    }

    @Test fun framesMatchReferenceInOrder() {
        val d = GifDecoder(gif)
        val out = IntArray(d.width * d.height)
        for (i in 0 until d.frameCount) {
            d.renderFrame(i, out)
            assertEquals("frame $i", expected[i], checksum(out))
        }
    }

    @Test fun seekingBackwardsRestarts() {
        val d = GifDecoder(gif)
        val out = IntArray(d.width * d.height)
        d.renderFrame(4, out)
        d.renderFrame(2, out)
        assertEquals(expected[2], checksum(out))
        d.renderFrame(3, out)
        assertEquals(expected[3], checksum(out))
    }

    @Test fun indexAtFollowsDelaysAndLoops() {
        val d = GifDecoder(gif)
        assertEquals(0, d.indexAt(0))
        assertEquals(0, d.indexAt(49))
        assertEquals(1, d.indexAt(50))
        assertEquals(2, d.indexAt(150))
        assertEquals(3, d.indexAt(180))
        assertEquals(4, d.indexAt(d.durationMs - 1))
        assertEquals(0, d.indexAt(d.durationMs))
    }

    @Test fun rejectsNonGif() {
        var failed = false
        try { GifDecoder(ByteArray(40)) } catch (e: java.io.IOException) { failed = true }
        assertTrue(failed)
    }
